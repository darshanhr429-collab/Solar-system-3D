// VSOP87 truncated planetary ephemeris: J2000 heliocentric ecliptic coordinates.
// Full VSOP87 data is several megabytes; here terms with amplitude < 0.001" are truncated (~50-100KB),
// maintaining < 0.1 deg accuracy vs JPL Horizons (-3000 to +3000 AD).
//
// Original VSOP87 L/B/R series are in the dynamical ecliptic of date, requiring precession transformation
// to convert back to the J2000 ecliptic frame (co-registered with Standish elements in planets.js).
// Uses IAU 1976 precession angles and 3D rotation matrices.
//
// References:
//   Francou, G., Berthier, M., 1998, "VSOP87 solutions"
//   Meeus, J., "Astronomical Algorithms", 2nd ed., Ch. 25/31

import { centuriesTT } from './time.js';
import { KM_PER_AU } from './kepler.js';

// ── VSOP87 Truncated Data (auto-generated by tools/fetch-vsop87.mjs from astronomia) ──
import { VSOP87_DATA } from './vsop87Data.js';

// Pluto is not included in VSOP87; key remains null and falls back to approximate elements at runtime
const DATA = { ...VSOP87_DATA, pluto: null };

// ── Precession Rotation: Dynamical Ecliptic of Date -> J2000 Mean Ecliptic ──
// VSOP87 L/B/R are in the dynamical ecliptic of date;
// 3D rotation converts to J2000 ecliptic frame.
// Method: Ecliptic(date) -> Equatorial(date) -> Precession -> Equatorial(J2000) -> Ecliptic(J2000).
// Precession angles use IAU 1976 (Lieske et al.), error < 0.01 deg over +/-3000 years.

const ASEC = Math.PI / (180 * 3600); // Arcseconds -> radians
const EPS0 = 23.43929111 * Math.PI / 180; // J2000 mean obliquity of the ecliptic

/** 3x3 row-major matrix multiply (v' = M*v convention, same family as Rx/Rz in rotation.js) */
function mm3(a, b) {
  const r = new Array(9);
  for (let i = 0; i < 3; i++)
    for (let j = 0; j < 3; j++)
      r[i * 3 + j] = a[i * 3] * b[j] + a[i * 3 + 1] * b[3 + j] + a[i * 3 + 2] * b[6 + j];
  return r;
}
const Rxm = (t) => [1, 0, 0, 0, Math.cos(t), Math.sin(t), 0, -Math.sin(t), Math.cos(t)];
const Rzm = (t) => [Math.cos(t), Math.sin(t), 0, -Math.sin(t), Math.cos(t), 0, 0, 0, 1];
// Note: SOFA/IAU Ry has inverted sign convention relative to Rx/Rz; cannot share the same helper
const RymSOFA = (t) => [Math.cos(t), 0, Math.sin(t), 0, 1, 0, -Math.sin(t), 0, Math.cos(t)];

/** Compute precession rotation matrix (date -> J2000), returns 3x3 row-major array */
function precessionMatrix(T) {
  // IAU 1976 precession angles (arcseconds)
  const zeta = (2306.2181 * T + 0.30188 * T * T + 0.017998 * T * T * T) * ASEC;
  const z = (2306.2181 * T + 1.09468 * T * T + 0.018203 * T * T * T) * ASEC;
  const theta = (2004.3109 * T - 0.42665 * T * T - 0.041833 * T * T * T) * ASEC;
  // Instantaneous mean obliquity of the ecliptic
  const eps = EPS0 + (-46.8150 * T - 0.00059 * T * T + 0.001813 * T * T * T) * ASEC;

  // v_eclJ2000 = Rx(−ε0) · Rz(−z) · Ry(θ) · Rz(−ζ) · Rx(+ε) · v_eclDate
  const P = mm3(Rzm(-z), mm3(RymSOFA(theta), Rzm(-zeta)));
  return mm3(Rxm(-EPS0), mm3(P, Rxm(eps)));
}

// ── VSOP87 Series Evaluation ──────────────────────────────────────────
/** Evaluate L0 + L1*T + L2*T^2 + ..., where each term = sum(A * cos(B + C*T)) */
function evalSeries(series, T) {
  let sum = 0;
  let tPow = 1;
  for (let n = 0; n < series.length; n++) {
    const terms = series[n];
    let s = 0;
    for (let i = 0; i < terms.length; i++) {
      const t = terms[i];
      s += t[0] * Math.cos(t[1] + t[2] * T);
    }
    sum += s * tPow;
    tPow *= T;
  }
  return sum;
}

/**
 * VSOP87 planetary heliocentric position (Ecliptic J2000, km).
 * @param {string} bodyId mercury|venus|earth|emb|mars|jupiter|saturn|uranus|neptune|pluto
 * @param {number} jdTT Julian Date in TT
 * @returns {{x:number, y:number, z:number}} Heliocentric Ecliptic J2000 coordinates (km)
 */
export function planetaryPositionVSOP(bodyId, jdTT) {
  const Tcy = centuriesTT(jdTT);
  // VSOP87 series time unit is Julian millennia, not centuries:
  // Coefficient check: Earth L1 = 6283.076 rad/millennium (1000 revs), 26087.903 = Mercury rad/millennium.
  const T = Tcy / 10;

  // Pluto not in VSOP87: fallback to approximate elements
  if (bodyId === 'pluto') {
    // Approximate with Standish elements (inline to avoid circular dependencies)
    // Direct simplified Keplerian evaluation
    return plutoApprox(jdTT);
  }

  const data = DATA[bodyId] || DATA[bodyId === 'emb' ? 'earth' : bodyId];
  if (!data) throw new Error(`VSOP87: unknown body "${bodyId}"`);

  // Spherical coordinates in dynamical ecliptic of date
  const L = evalSeries(data.L, T);
  const B = evalSeries(data.B, T);
  const R = evalSeries(data.R, T);

  // Spherical -> Cartesian (dynamical ecliptic of date)
  const cosB = Math.cos(B);
  const x0 = R * cosB * Math.cos(L);
  const y0 = R * cosB * Math.sin(L);
  const z0 = R * Math.sin(B);

  // Precession rotation -> J2000 ecliptic (IAU 1976 coefficients in Julian centuries)
  // Transposed precession matrix transforms date -> J2000
  const m = precessionMatrix(Tcy);
  const x = m[0] * x0 + m[3] * y0 + m[6] * z0;
  const y = m[1] * x0 + m[4] * y0 + m[7] * z0;
  const z = m[2] * x0 + m[5] * y0 + m[8] * z0;

  return { x: x * KM_PER_AU, y: y * KM_PER_AU, z: z * KM_PER_AU };
}

/** Approximate Pluto position (Standish element fallback as VSOP87 excludes Pluto) */
function plutoApprox(jdTT) {
  // Matches TABLE.pluto in planets.js, inlined to prevent circular dependencies
  const T = centuriesTT(jdTT);
  const aAU = 39.48211675 - 0.00031596 * T;
  const e = 0.24882730 + 0.00005170 * T;
  const iDeg = 17.14001206 + 0.00004818 * T;
  const LDeg = 238.92903833 + 145.20780515 * T;
  const periDeg = 224.06891629 - 0.04062942 * T;
  const nodeDeg = 110.30393684 - 0.01183482 * T;
  const DEG = Math.PI / 180;
  const omega = (periDeg - nodeDeg) * DEG;
  const M = (LDeg - periDeg) * DEG;
  // Newton-Raphson Kepler solver
  let E = M;
  for (let k = 0; k < 20; k++) {
    const dE = (E - e * Math.sin(E) - M) / (1 - e * Math.cos(E));
    E -= dE;
    if (Math.abs(dE) < 1e-12) break;
  }
  const xp = aAU * (Math.cos(E) - e);
  const yp = aAU * Math.sqrt(1 - e * e) * Math.sin(E);
  const cw = Math.cos(omega), sw = Math.sin(omega);
  const cO = Math.cos(nodeDeg * DEG), sO = Math.sin(nodeDeg * DEG);
  const ci = Math.cos(iDeg * DEG), si = Math.sin(iDeg * DEG);
  const x = (cw * cO - sw * sO * ci) * xp + (-sw * cO - cw * sO * ci) * yp;
  const y = (cw * sO + sw * cO * ci) * xp + (-sw * sO + cw * cO * ci) * yp;
  const z = (sw * si) * xp + (cw * si) * yp;
  return { x: x * KM_PER_AU, y: y * KM_PER_AU, z: z * KM_PER_AU };
}

/** Whether VSOP87 supports the specified celestial body */
export function vsop87Supported(bodyId) {
  return bodyId !== 'pluto' && DATA[bodyId] != null;
}
