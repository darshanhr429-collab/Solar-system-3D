// Moon position propagation: osculating elements fitted from Horizons (moonsData.generated.js).
// Returns Ecliptic J2000 coordinates relative to parent planet center (km).
//
// Secular rates model (empirical lambda/varpi/Omega decomposition, see tools/fit-moons.mjs):
//   Omega(t) = Omega0 + Omega_dot*dt, varpi(t) = varpi0 + varpi_dot*dt, M(t) = M0 + n*dt, where n = lambda_dot - varpi_dot
// Guarantees exact agreement with Horizons at fit epochs, first-order node regression and periapsis precession.
// When rates are missing, defaults gracefully to zero.

import { elementsToEcliptic, KM_PER_AU } from './kepler.js';
